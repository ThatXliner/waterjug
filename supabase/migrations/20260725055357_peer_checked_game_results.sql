CREATE TABLE public.game_results (
  id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  game_id bigint NOT NULL REFERENCES public.games(game_id) ON DELETE CASCADE,
  reporter_id uuid NOT NULL REFERENCES auth.users(id) ON DELETE CASCADE,
  submission_id uuid NOT NULL,
  winner_id uuid NOT NULL,
  loser_id uuid NOT NULL,
  status text NOT NULL DEFAULT 'pending'
    CHECK (status IN ('pending', 'confirmed', 'disputed')),
  configuration_revision bigint NOT NULL DEFAULT 1 CHECK (configuration_revision > 0),
  rating_configuration_snapshot jsonb NOT NULL DEFAULT '{}'::jsonb,
  winner_rating_snapshot double precision NOT NULL DEFAULT 0,
  winner_type_snapshot text NOT NULL DEFAULT '',
  winner_other_data_snapshot jsonb NOT NULL DEFAULT '{}'::jsonb,
  loser_rating_snapshot double precision NOT NULL DEFAULT 0,
  loser_type_snapshot text NOT NULL DEFAULT '',
  loser_other_data_snapshot jsonb NOT NULL DEFAULT '{}'::jsonb,
  reviewed_by uuid REFERENCES auth.users(id) ON DELETE SET NULL,
  reviewed_at timestamptz,
  created_at timestamptz NOT NULL DEFAULT now(),
  updated_at timestamptz NOT NULL DEFAULT now(),
  CHECK (winner_id <> loser_id),
  CHECK (reporter_id = winner_id OR reporter_id = loser_id),
  CHECK (
    (status = 'pending' AND reviewed_by IS NULL AND reviewed_at IS NULL)
    OR
    (status IN ('confirmed', 'disputed') AND reviewed_by IS NOT NULL AND reviewed_at IS NOT NULL)
  ),
  FOREIGN KEY (game_id, winner_id)
    REFERENCES public.ratings(game_id, user_id) ON DELETE CASCADE,
  FOREIGN KEY (game_id, loser_id)
    REFERENCES public.ratings(game_id, user_id) ON DELETE CASCADE,
  UNIQUE (reporter_id, submission_id)
);

CREATE INDEX game_results_participant_status_idx
  ON public.game_results (game_id, status, created_at DESC);
CREATE INDEX game_results_winner_idx
  ON public.game_results (winner_id, created_at DESC);
CREATE INDEX game_results_loser_idx
  ON public.game_results (loser_id, created_at DESC);

ALTER TABLE public.game_results ENABLE ROW LEVEL SECURITY;

CREATE POLICY "Current participants can view accessible game results"
  ON public.game_results
  FOR SELECT
  TO authenticated
  USING (
    (SELECT auth.uid()) IN (winner_id, loser_id)
    AND EXISTS (
      SELECT 1
      FROM public.games
      WHERE games.game_id = game_results.game_id
    )
  );

CREATE POLICY "Current participants can report accessible game results"
  ON public.game_results
  FOR INSERT
  TO authenticated
  WITH CHECK (
    reporter_id = (SELECT auth.uid())
    AND reporter_id IN (winner_id, loser_id)
    AND EXISTS (
      SELECT 1
      FROM public.games
      WHERE games.game_id = game_results.game_id
    )
  );

CREATE OR REPLACE FUNCTION public.prepare_game_result()
RETURNS trigger
LANGUAGE plpgsql
SECURITY INVOKER
SET search_path = ''
AS $$
DECLARE
  current_user_id uuid := auth.uid();
  current_revision bigint;
  current_configuration jsonb;
  winner_row public.ratings%ROWTYPE;
  loser_row public.ratings%ROWTYPE;
BEGIN
  IF current_user_id IS NULL THEN
    RAISE EXCEPTION 'Authentication required' USING ERRCODE = '42501';
  END IF;

  IF NEW.winner_id = NEW.loser_id THEN
    RAISE EXCEPTION 'Winner and loser must be different players' USING ERRCODE = '22023';
  END IF;

  IF current_user_id NOT IN (NEW.winner_id, NEW.loser_id) THEN
    RAISE EXCEPTION 'Only a participant can report this result' USING ERRCODE = '42501';
  END IF;

  PERFORM pg_advisory_xact_lock(NEW.game_id);

  SELECT games.rating_configuration_revision, games.rating_configuration::jsonb
  INTO current_revision, current_configuration
  FROM public.games
  WHERE games.game_id = NEW.game_id
  FOR SHARE;

  IF NOT FOUND THEN
    RAISE EXCEPTION 'Game not found or no longer accessible' USING ERRCODE = '42501';
  END IF;

  PERFORM 1
  FROM public.ratings
  WHERE ratings.game_id = NEW.game_id
    AND ratings.user_id IN (NEW.winner_id, NEW.loser_id)
  ORDER BY ratings.user_id
  FOR UPDATE;

  SELECT *
  INTO winner_row
  FROM public.ratings
  WHERE game_id = NEW.game_id
    AND user_id = NEW.winner_id;

  SELECT *
  INTO loser_row
  FROM public.ratings
  WHERE game_id = NEW.game_id
    AND user_id = NEW.loser_id;

  IF winner_row.user_id IS NULL OR loser_row.user_id IS NULL THEN
    RAISE EXCEPTION 'Both players must have a rating in this game' USING ERRCODE = '23503';
  END IF;

  NEW.reporter_id := current_user_id;
  NEW.status := 'pending';
  NEW.configuration_revision := current_revision;
  NEW.rating_configuration_snapshot := current_configuration;
  NEW.winner_rating_snapshot := winner_row.rating;
  NEW.winner_type_snapshot := winner_row.type;
  NEW.winner_other_data_snapshot := winner_row.other_data::jsonb;
  NEW.loser_rating_snapshot := loser_row.rating;
  NEW.loser_type_snapshot := loser_row.type;
  NEW.loser_other_data_snapshot := loser_row.other_data::jsonb;
  NEW.reviewed_by := NULL;
  NEW.reviewed_at := NULL;
  NEW.created_at := COALESCE(NEW.created_at, now());
  NEW.updated_at := now();

  RETURN NEW;
END;
$$;

CREATE TRIGGER prepare_game_result_before_insert
  BEFORE INSERT ON public.game_results
  FOR EACH ROW
  EXECUTE FUNCTION public.prepare_game_result();

CREATE OR REPLACE FUNCTION public.review_game_result(
  p_result_id bigint,
  p_reviewer_id uuid,
  p_decision text,
  p_expected_configuration_revision bigint,
  p_winner_new_rating double precision DEFAULT NULL,
  p_winner_new_type text DEFAULT NULL,
  p_winner_new_other_data jsonb DEFAULT NULL,
  p_loser_new_rating double precision DEFAULT NULL,
  p_loser_new_type text DEFAULT NULL,
  p_loser_new_other_data jsonb DEFAULT NULL
)
RETURNS public.game_results
LANGUAGE plpgsql
SECURITY DEFINER
SET search_path = ''
AS $$
DECLARE
  result_row public.game_results%ROWTYPE;
  target_game_id bigint;
  current_revision bigint;
  current_configuration jsonb;
  game_owner_id uuid;
  game_is_private boolean;
  reviewer_email text;
  winner_row public.ratings%ROWTYPE;
  loser_row public.ratings%ROWTYPE;
BEGIN
  IF p_decision NOT IN ('confirmed', 'disputed') THEN
    RAISE EXCEPTION 'Decision must be confirmed or disputed' USING ERRCODE = '22023';
  END IF;

  IF p_reviewer_id IS NULL THEN
    RAISE EXCEPTION 'Reviewer is required' USING ERRCODE = '42501';
  END IF;

  SELECT game_id
  INTO target_game_id
  FROM public.game_results
  WHERE id = p_result_id;

  IF NOT FOUND THEN
    RAISE EXCEPTION 'Result not found' USING ERRCODE = 'P0002';
  END IF;

  PERFORM pg_advisory_xact_lock(target_game_id);

  SELECT *
  INTO result_row
  FROM public.game_results
  WHERE id = p_result_id
    AND game_id = target_game_id
  FOR UPDATE;

  IF NOT FOUND THEN
    RAISE EXCEPTION 'Result not found' USING ERRCODE = 'P0002';
  END IF;

  IF p_reviewer_id NOT IN (result_row.winner_id, result_row.loser_id)
     OR p_reviewer_id = result_row.reporter_id THEN
    RAISE EXCEPTION 'Only the opponent can review this result' USING ERRCODE = '42501';
  END IF;

  SELECT
    games.rating_configuration_revision,
    games.rating_configuration::jsonb,
    games.created_by,
    games.invite_only,
    lower(users.email)
  INTO current_revision, current_configuration, game_owner_id, game_is_private, reviewer_email
  FROM public.games
  JOIN auth.users AS users ON users.id = p_reviewer_id
  WHERE games.game_id = result_row.game_id
  FOR SHARE OF games;

  IF NOT FOUND THEN
    RAISE EXCEPTION 'Game or reviewer not found' USING ERRCODE = '42501';
  END IF;

  IF game_is_private
     AND p_reviewer_id <> game_owner_id
     AND NOT EXISTS (
       SELECT 1
       FROM public.game_invites
       WHERE game_invites.game_id = result_row.game_id
         AND game_invites.invited_email = reviewer_email
     ) THEN
    RAISE EXCEPTION 'Reviewer no longer has access to this private game' USING ERRCODE = '42501';
  END IF;

  IF result_row.status <> 'pending' THEN
    IF result_row.status = p_decision AND result_row.reviewed_by = p_reviewer_id THEN
      RETURN result_row;
    END IF;

    RAISE EXCEPTION 'Result has already been reviewed as %', result_row.status
      USING ERRCODE = '22023';
  END IF;

  IF p_decision = 'disputed' THEN
    UPDATE public.game_results
    SET status = 'disputed',
        reviewed_by = p_reviewer_id,
        reviewed_at = now(),
        updated_at = now()
    WHERE id = result_row.id
    RETURNING * INTO result_row;

    RETURN result_row;
  END IF;

  IF p_expected_configuration_revision IS DISTINCT FROM result_row.configuration_revision
     OR current_revision IS DISTINCT FROM result_row.configuration_revision
     OR current_configuration IS DISTINCT FROM result_row.rating_configuration_snapshot THEN
    RAISE EXCEPTION 'Rating configuration changed after this result was reported'
      USING ERRCODE = 'PT409';
  END IF;

  IF p_winner_new_rating IS NULL
     OR p_winner_new_type IS NULL
     OR p_winner_new_other_data IS NULL
     OR p_loser_new_rating IS NULL
     OR p_loser_new_type IS NULL
     OR p_loser_new_other_data IS NULL THEN
    RAISE EXCEPTION 'Confirmed results require both calculated rating updates'
      USING ERRCODE = '22023';
  END IF;

  PERFORM 1
  FROM public.ratings
  WHERE ratings.game_id = result_row.game_id
    AND ratings.user_id IN (result_row.winner_id, result_row.loser_id)
  ORDER BY ratings.user_id
  FOR UPDATE;

  SELECT *
  INTO winner_row
  FROM public.ratings
  WHERE game_id = result_row.game_id
    AND user_id = result_row.winner_id;

  SELECT *
  INTO loser_row
  FROM public.ratings
  WHERE game_id = result_row.game_id
    AND user_id = result_row.loser_id;

  IF winner_row.user_id IS NULL OR loser_row.user_id IS NULL THEN
    RAISE EXCEPTION 'A participant rating no longer exists' USING ERRCODE = 'PT409';
  END IF;

  IF winner_row.rating IS DISTINCT FROM result_row.winner_rating_snapshot
     OR winner_row.type IS DISTINCT FROM result_row.winner_type_snapshot
     OR winner_row.other_data::jsonb IS DISTINCT FROM result_row.winner_other_data_snapshot
     OR loser_row.rating IS DISTINCT FROM result_row.loser_rating_snapshot
     OR loser_row.type IS DISTINCT FROM result_row.loser_type_snapshot
     OR loser_row.other_data::jsonb IS DISTINCT FROM result_row.loser_other_data_snapshot THEN
    RAISE EXCEPTION 'A participant rating changed after this result was reported'
      USING ERRCODE = 'PT409';
  END IF;

  UPDATE public.ratings
  SET rating = p_winner_new_rating,
      type = p_winner_new_type,
      other_data = p_winner_new_other_data::json
  WHERE game_id = result_row.game_id
    AND user_id = result_row.winner_id;

  UPDATE public.ratings
  SET rating = p_loser_new_rating,
      type = p_loser_new_type,
      other_data = p_loser_new_other_data::json
  WHERE game_id = result_row.game_id
    AND user_id = result_row.loser_id;

  UPDATE public.game_results
  SET status = 'confirmed',
      reviewed_by = p_reviewer_id,
      reviewed_at = now(),
      updated_at = now()
  WHERE id = result_row.id
  RETURNING * INTO result_row;

  RETURN result_row;
END;
$$;

